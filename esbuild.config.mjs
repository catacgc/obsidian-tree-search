import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import tailwindPlugin from "esbuild-plugin-tailwindcss";
import nested from "postcss-nested";
import fs from "fs";
import path from "path";

// Plugin to inline .wasm files as base64 strings.
// Intercepts explicit `.wasm` imports and replaces them with a module
// exporting the binary content as a base64 string.
const wasmInlinePlugin = {
	name: 'wasm-inline',
	setup(build) {
		build.onResolve({ filter: /\.wasm$/ }, (args) => {
			const resolved = path.resolve(args.resolveDir, args.path);
			return { path: resolved, namespace: 'wasm-inline' };
		});
		build.onLoad({ filter: /.*/, namespace: 'wasm-inline' }, (args) => {
			const bytes = fs.readFileSync(args.path);
			const base64 = Buffer.from(bytes).toString('base64');
			return {
				contents: `export default "${base64}"`,
				loader: 'js',
			};
		});
	},
};

// Plugin to copy files to dist
const copyFilesPlugin = {
	name: 'copy-files',
	setup(build) {
		build.onEnd(() => {
			const filesToCopy = ['.hotreload', 'manifest.json', 'manifest-beta.json'];
			filesToCopy.forEach(file => {
				fs.copyFileSync(file, path.join('dist', file));
			});
		});
	},
};

const banner =
	`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = (process.argv[2] === "production");

const esbuildOptions = {
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts", "src/view/styles.css"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
		...builtins.map(m => `node:${m}`),
	],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outdir: "dist",
	entryNames: "[name]",
	// Suppress esbuild's default file-loader for .wasm references (e.g., the
	// `new URL('...wasm', import.meta.url)` pattern in wasm-pack glue code).
	// The wasmInlinePlugin onResolve/onLoad hooks take priority for explicit
	// .wasm imports; this loader config prevents asset emission for other
	// static references esbuild encounters during bundling.
	loader: { '.wasm': 'empty' },
	plugins: [
		wasmInlinePlugin,
		tailwindPlugin({ 
			output: "dist/styles.css",
			postcssPlugins: {
				append: [
					nested() // puts the preflight from tailwindcss only in .tw-reset (see styles.css)
				]
			}
		}),
		copyFilesPlugin,
	],
}

const context = await esbuild.context(
	{...esbuildOptions}
);

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
